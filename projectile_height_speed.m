% [실습 4-2] 예제 4.3-1 발사체의 높이와 속도 (4장 MATLAB 프로그래밍)
% 높이가 6 m보다 작지 않고(h >= 6), 동시에 속력이 16 m/s보다 크지 않은(v <= 16) 시간을 구한다.
% 관계 연산자(>=, <=)와 논리 연산자(&), find 함수를 이용한 풀이
%
%   h(t) = v0*t*sin(A) - 0.5*g*t^2
%   v(t) = sqrt(v0^2 - 2*v0*g*t*sin(A) + g^2*t^2)
%   t_hit = 2*(v0/g)*sin(A)  (땅에 충돌하는 시간)

v0 = 20;                 % 발사 속도 (m/s)
g = 9.81;                % 중력가속도 (m/s^2)
A = 40*pi/180;           % 발사 각도 (40도 -> rad)

% 충돌 시까지의 시간
t_hit = 2*v0*sin(A)/g;

% 0 ~ t_hit 를 100 구간으로 나눈 시간 배열
t = 0:t_hit/100:t_hit;

% 각 시간에서의 높이와 속력 (t가 배열이므로 .^ 사용)
h = v0*t*sin(A) - 0.5*g*t.^2;
v = sqrt(v0^2 - 2*v0*g*sin(A)*t + g^2*t.^2);

% 두 조건을 동시에 만족하는 원소의 인덱스
u = find(h >= 6 & v <= 16);

% 조건을 만족하는 시간 구간의 시작과 끝
t_1 = t(u(1))            % 답: 0.8649 (s)
t_2 = t(u(end))          % 답: 1.7560 (s)

% [접근 방법에 관한 논의]
% 1. 시간을 잘게 나눈 배열 t를 만들고 각 시간에서 h와 v를 계산한 뒤,
%    관계 연산자로 두 조건을 각각 판정하고 &로 동시에 만족하는 원소를 고른다.
% 2. 조건을 만족하는 구간이 하나로 이어져 있다고 보고 첫 번째와 마지막 인덱스로 구간을 정한다.
%    (h는 위로 볼록, v는 꼭대기에서 가장 작으므로 구간은 하나로 이어진다.)
% 3. 답의 정확도는 시간 간격(t_hit/100 = 약 0.026 s)에 달려 있다.
%    h = 6, v = 16 을 직접 풀면 0.8403 <= t <= 1.7806 이며,
%    간격을 더 작게 하면 계산 결과가 이 값에 가까워진다.
