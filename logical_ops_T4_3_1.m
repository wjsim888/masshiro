% [실습] T4.3-1 논리 연산자 (4장 MATLAB 프로그래밍)
% x = [5, -3, 18, 4], y = [-9, 13, 7, 4] 일 때 논리 연산의 결과를 구한다.
% 숫자를 논리 연산에 쓰면 0은 거짓(0), 0이 아닌 값은 참(1)으로 취급된다.

x = [5, -3, 18, 4];
y = [-9, 13, 7, 4];

% a. ~ 는 > 보다 우선순위가 높으므로 (~y) > x 로 계산된다.
%    ~y = [0, 0, 0, 0] (y에 0이 없음) -> 0 > x
%    답: [0, 1, 0, 0]
z_a = ~y > x

% b. AND: 둘 다 0이 아니면 1
%    답: [1, 1, 1, 1]
z_b = x & y

% c. OR: 둘 중 하나라도 0이 아니면 1
%    답: [1, 1, 1, 1]
z_c = x | y

% d. 배타적 OR: 둘 중 정확히 하나만 0이 아니면 1
%    답: [0, 0, 0, 0]
z_d = xor(x, y)
