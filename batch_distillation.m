% [실습] 일괄처리(batch) 증류 공정 (W4, 2장 수치/셀/구조체 배열 (2))
% 강의록의 배열 나눗셈(./), 배열 지수승(.^), 원소-대-원소 곱셈(.*)을 이용한 풀이
%
%   L = 100 * (x/0.6)^0.625 * ((1-x)/0.4)^(-1.625)
%   L = 70 일 때 남아 있는 벤젠의 몰 비율 x를 구한다.

% 벤젠의 몰 비율 x (처음 0.6에서 증류가 진행되며 줄어든다)
x = 0.4:0.0001:0.6;

% 증류기에 남아 있는 액체의 양 L (x의 각 원소마다 계산)
L = 100 * (x./0.6).^0.625 .* ((1-x)./0.4).^(-1.625);

% x 대 L 그래프 (점선: L = 70)
plot(x, L, [0.4, 0.6], [70, 70], '--')
xlabel('x (mol B/mol)')
ylabel('L (mol)')
title('일괄처리 증류 공정')
grid on

% L = 70 에 가장 가까운 점을 찾아 x 값을 숫자로 출력
[diff_min, k] = min(abs(L - 70));
x_70 = x(k)        % 벤젠의 몰 비율
L_70 = L(k)        % 그때의 L 값
