% [실습] 일괄처리(batch) 증류 공정 (W4, 2장 수치/셀/구조체 배열 (2))
% L = 100*(x/0.6)^0.625 * ((1-x)/0.4)^(-1.625)
% L = 70 일 때의 벤젠 몰 비율 x를 그래프에서 읽는다.

% 벤젠 몰 비율 x (처음 0.6에서 증류가 진행되며 줄어든다)
x = 0.4:0.0001:0.6;

% 배열 지수승(.^)과 원소-대-원소 곱셈(.*) 사용
L = 100*(x/0.6).^0.625 .* ((1-x)/0.4).^(-1.625);

% x 대 L 그래프
plot(x, L, [0.4, 0.6], [70, 70], '--')
xlabel('x (mol B/mol)')
ylabel('L (mol)')
title('일괄처리 증류 공정')
grid on

% L = 70 에 가장 가까운 점의 x 값을 숫자로 구한다
% (수송 경로 분석 예제처럼 [값, 위치] = min(...) 사용)
[diff_min, k] = min(abs(L - 70));
x_70 = x(k)        % 벤젠의 몰 비율 (약 0.5263)
L_70 = L(k)        % 그때의 L 값 (약 70.00)
