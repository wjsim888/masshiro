% [실습] T3.2-4 함수의 최소점 (W6, 3장 함수 (1))
% 구간 0 < x < 10 에서 y = 1 + e^(-0.2x) sin(x+2) 의 두 최소점 (x, y) 를 구한다.
% 강의록의 사용자 정의 함수(f_T3_2_4.m), 함수 핸들(@), fminbnd 를 이용한 풀이

% 1) 그래프로 최소점의 대략적인 위치를 찾는다
x = 0:0.01:10;
plot(x, f_T3_2_4(x)), xlabel('x'), ylabel('y'), grid
% 그래프에서 x = 2.5 근처와 x = 9 근처에 최소점이 있고, x = 5.7 근처에 최대점이 있다

% 2) fminbnd 는 한 구간에서 최소점 하나만 찾으므로, 최소점이 하나씩 들어가도록 구간을 나눈다
%    fminbnd 는 최소가 되는 x 만 반환하므로, y 값은 함수에 x 를 넣어 따로 구한다
xa = fminbnd(@f_T3_2_4, 0, 5)      % 첫 번째 최소점: 0 <= x <= 5
ya = f_T3_2_4(xa)

xb = fminbnd(@f_T3_2_4, 6, 10)     % 두 번째 최소점: 6 <= x <= 10
yb = f_T3_2_4(xb)

% 결과: (xa, ya) = (2.5150, 0.4070), (xb, yb) = (8.7982, 0.8312)
%
% 교재 답의 두 번째 점 (9.0001, 0.8347) 은 구간을 9 <= x <= 10 으로 잡았을 때 나오는 값이다.
%   fminbnd(@f_T3_2_4, 9, 10)  ->  9.0001
% 이 구간 안에는 최소점이 없어서, fminbnd 가 구간의 끝(경계) x = 9 를 반환한 것이다.
% (강의록: "fminbnd 는 경계에서 발생하는 최소값을 구한다")
% 실제 최소점은 x = 8.7982 이고, y(8.7982) = 0.8312 가 y(9.0001) = 0.8347 보다 작다.
