% [연습문제] 23. 익명 함수 (3장 함수와 파일)
% 10e^(-2x) 에 대한 익명 함수를 생성하고, 이것을 사용하여 0 <= x <= 2 에서 그래프를 그린다.

% 익명 함수 f(x) = 10e^(-2x)
% x에 배열을 넣어도 계산되도록 원소-대-원소 연산을 사용
f = @(x) 10*exp(-2*x);

% 구간 0 <= x <= 2
x = 0:0.01:2;

% 익명 함수로 f(x) 값을 계산하여 그래프를 그림
plot(x, f(x))
xlabel('x')
ylabel('f(x)')
title('f(x) = 10e^{-2x}')
grid on
