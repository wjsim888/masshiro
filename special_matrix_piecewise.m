% [실습] 특수한 행렬의 활용 (W5, 2장 수치/셀/구조체 배열 (3))
% ones, zeros 함수로 구간별 f(x) 값을 생성하여 그래프를 그린다.
%
%          10    (0 <= x <= 2)
%   f(x) =  0    (2 <  x <  5)
%          -3    (5 <= x <= 7)

% 구간 1: 0 <= x <= 2 -> f(x) = 10
x1 = 0:0.01:2;
f1 = 10*ones(size(x1));

% 구간 2: 2 < x < 5 -> f(x) = 0 (끝점 2와 5는 제외)
x2 = 2.01:0.01:4.99;
f2 = zeros(size(x2));

% 구간 3: 5 <= x <= 7 -> f(x) = -3
x3 = 5:0.01:7;
f3 = -3*ones(size(x3));

% 세 구간을 하나의 배열로 연결
x = [x1, x2, x3];
f = [f1, f2, f3];

% 그래프
plot(x, f)
xlabel('x')
ylabel('f(x)')
title('f(x) 그래프')
axis([0, 7, -5, 12])   % f = 10, -3 선이 그래프 테두리에 붙지 않도록 범위 지정
grid on
