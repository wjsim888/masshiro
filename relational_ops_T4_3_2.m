% [실습] T4.3-2 관계 연산자 (4장 MATLAB 프로그래밍)
% x = [-9, -6, 0, 2, 5], y = [-10, -6, 2, 4, 6] 일 때 관계 연산의 결과를 구한다.
% 관계 연산은 원소-대-원소로 비교하여 참이면 1, 거짓이면 0을 준다.

x = [-9, -6, 0, 2, 5];
y = [-10, -6, 2, 4, 6];

% a. 답: [0, 0, 1, 1, 1]
z_a = (x < y)

% b. 답: [1, 0, 0, 0, 0]
z_b = (x > y)

% c. 답: [1, 0, 1, 1, 1]
z_c = (x ~= y)

% d. 답: [0, 1, 0, 0, 0]
z_d = (x == y)

% e. 배열과 스칼라 비교: x의 각 원소를 2와 비교
%    답: [0, 0, 0, 0, 1]
z_e = (x > 2)
