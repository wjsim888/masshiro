% [실습] 생산 비용 분석-2 (W4, 2장 수치/셀/구조체 배열 (2))
% 강의록의 행렬-행렬 곱셈(*)을 이용한 풀이 (단위: $ x 10^3)

% [표 2.4-3] 단위 비용 (행: 재료비, 인건비, 운송비 / 열: 생산품 1, 2, 3, 4)
U = [6, 2, 4, 9;
     2, 5, 3, 7;
     1, 4, 2, 3];

% [표 2.4-4] 분기별 생산량 (행: 생산품 1, 2, 3, 4 / 열: 1/4 ~ 4/4분기)
P = [10, 12, 13, 15;
      8,  7,  6,  4;
     12, 10, 13,  9;
      6,  4, 11,  5];

% 분기별 재료비, 인건비, 운송비
% (3x4) * (4x4) = (3x4) -> 행: 재료비, 인건비, 운송비 / 열: 분기
C = U * P

% 한 해 동안의 총 재료비, 인건비, 운송비 (각 행의 합)
% (3x4) * (4x1) = (3x1)
annual_cost = C * [1; 1; 1; 1]

% 분기별 총 비용 (각 열의 합)
% (1x3) * (3x4) = (1x4)
quarter_cost = [1, 1, 1] * C
