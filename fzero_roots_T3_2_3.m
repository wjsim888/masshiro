% [실습] T3.2-3 방정식의 해 (W6, 3장 함수 (1))
% 구간 0 < x < 10 에서 e^(-0.2x) sin(x+2) = 0.1 의 해 세 개를 구한다.
% 강의록의 사용자 정의 함수(f_T3_2_3.m), 함수 핸들(@), fzero 를 이용한 풀이
% (교재 답: x = 1.0187, 4.5334, 7.0066)

% 1) f(x) = e^(-0.2x) sin(x+2) - 0.1 의 그래프로 x축과 교차하는 위치를 찾는다
x = 0:0.01:10;
plot(x, f_T3_2_3(x), [0, 10], [0, 0], '--'), xlabel('x'), ylabel('f(x)'), grid
% 그래프에서 x = 1, 4.5, 7 근처에서 x축과 교차한다

% 2) fzero 는 초기값 근처의 해 하나만 찾으므로, 교차점마다 초기값을 따로 준다
x1 = fzero(@f_T3_2_3, 1)
x2 = fzero(@f_T3_2_3, 4.5)
x3 = fzero(@f_T3_2_3, 7)

% 3) 확인: 해를 넣으면 f(x) 가 0 에 가까워야 한다
check = f_T3_2_3([x1, x2, x3])
