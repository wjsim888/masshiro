% [실습 4-4] T4.5-1 조건문 (4장 MATLAB 프로그래밍)
% 스칼라 x의 값에 따라 if/elseif/else 문으로 y를 계산하는 스크립트 파일
% 실행 방법: 명령 창에서 x 값을 먼저 정한 뒤 파일 이름을 입력한다.
%   >> x = -5; piecewise_if_T4_5_1
%   (스크립트는 명령 창과 같은 작업 공간을 쓰므로 명령 창의 x를 그대로 사용한다.)
%
%   y = sqrt(x^2 + 1)          (x < 0)
%   y = 3x + 1                 (0 <= x < 10)
%   y = 9sin(5x - 50) + 31     (x >= 10)
%
% 손 계산 (sin의 각도 단위는 rad)
%   x = -5 : y = sqrt(26)       = 5.0990
%   x =  5 : y = 3*5 + 1        = 16
%   x = 15 : y = 9sin(25) + 31  = 29.8091

if x < 0
   y = sqrt(x^2 + 1)
elseif x < 10              % 여기까지 왔으면 x >= 0 이므로 0 <= x < 10
   y = 3*x + 1
else                       % 나머지: x >= 10
   y = 9*sin(5*x - 50) + 31
end
