% [실습] T4.3-3 find 함수 (4장 MATLAB 프로그래밍)
% x = [-4, -1, 0, 2, 10], y = [-5, -2, 2, 5, 9] 일 때
% 대응되는 y의 원소보다 큰 값을 갖는 x의 원소의 값과 인덱스를 구한다.

x = [-4, -1, 0, 2, 10];
y = [-5, -2, 2, 5, 9];

% x > y -> [1, 1, 0, 0, 1]
% find: 0이 아닌 원소(참)의 인덱스를 돌려준다.
index = find(x > y)       % 답: [1, 2, 5]

% 그 인덱스에 있는 x의 원소 값
values = x(index)         % 답: [-4, -1, 10]
