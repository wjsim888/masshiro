% [실습] T3.2-4 함수의 최소점 (3장 함수와 파일)
% 0 < x < 10 에서 y = 1 + e^(-0.2x) sin(x+2) (f_T3_2_4.m)의 최소점 2개를 구한다.
%
% 교재 답: (2.5150, 0.4070), (9.0001, 0.8347)
% 두 번째 최소점은 실제로 x = 8.7982, y = 0.8312 이다.
%   y' = e^(-0.2x)(cos(x+2) - 0.2 sin(x+2)) = 0  ->  tan(x+2) = 5
%   x = atan(5) - 2 + 3*pi = 8.7982,  f_T3_2_4(8.7982) = 0.8312 < f_T3_2_4(9.0001) = 0.8347
% 교재 답은 구간을 [9 10]으로 잡아 구간 왼쪽 끝(x = 9) 근처 값이 나온 것으로 보인다.

% 1. 그래프로 최소점의 대략적인 위치 확인
fplot(@f_T3_2_4, [0 10]), grid on
xlabel('x'), ylabel('y')

% 2. 그래프에서 읽은 구간으로 fminbnd (구간 안에 최소점이 하나만 있도록 잡는다)
[x_a, y_a] = fminbnd(@f_T3_2_4, 0, 5)
[x_b, y_b] = fminbnd(@f_T3_2_4, 7, 10)

% 3. 찾은 최소점을 그래프에 표시
hold on
plot([x_a, x_b], [y_a, y_b], 'ro')
hold off
